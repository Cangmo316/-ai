"""
比邻AI · 对话意图的规则式识别

P1 只做三件事，够用且完全可解释：
1. 「今天要做什么」类问题 → 顺带把今日计划作为卡片发出去（card 事件真正投入使用）
2. 「吃药了没 / 打卡」类 → 同样挂计划卡，让老人能在对话里直接看到待办
3. 都不命中 → 不挂卡（避免每句话都甩一张卡，老人会烦）

真正的意图路由（function calling / 结构化意图分类）留给后面——现在多花的成本
换不来更好的效果，反而让"计划卡什么时候出现"变得不可预测、没法测。
"""

from __future__ import annotations

import re

# 「今天有什么安排 / 该干啥 / 提醒我 / 打卡」这一类
PLAN_INTENT = re.compile(
    r"(今天|今日|明天).{0,6}(做什么|干啥|干什么|安排|计划|该做|要做的)"
    r"|有什么安排|有啥安排|该做什么|今天吃什么药|吃什么药|提醒我|要打卡|打卡|我的计划|康养计划"
)


def needs_plan_card(text: str) -> bool:
    return bool(PLAN_INTENT.search(text or ""))
